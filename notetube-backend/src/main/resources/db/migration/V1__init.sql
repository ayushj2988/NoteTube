-- NoteTube schema v1. JSON payloads are stored as long VARCHAR (not TEXT/CLOB) so the same SQL runs on PostgreSQL and H2;
-- Jackson converts them in the application layer.

CREATE TABLE users (
    id            VARCHAR(40)  PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100),
    google_sub    VARCHAR(64)  UNIQUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE sessions (
    token_hash VARCHAR(64) PRIMARY KEY,
    user_id    VARCHAR(40) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_sessions_user    ON sessions (user_id);
CREATE INDEX idx_sessions_expires ON sessions (expires_at);

CREATE TABLE notes (
    id                  VARCHAR(40)  PRIMARY KEY,
    user_id             VARCHAR(40)  NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title               VARCHAR(300) NOT NULL,
    subject             VARCHAR(100),
    url                 VARCHAR(500),
    youtube_id          VARCHAR(20),
    channel             VARCHAR(200),
    thumbnail_url       VARCHAR(500),
    duration_sec        INTEGER,
    status              VARCHAR(12)  NOT NULL,
    progress_transcript INTEGER      NOT NULL DEFAULT 0,
    progress_notes      INTEGER      NOT NULL DEFAULT 0,
    progress_extras     INTEGER      NOT NULL DEFAULT 0,
    error_code          VARCHAR(30),
    error_message       VARCHAR(500),
    summary             VARCHAR(5000000),
    takeaways           VARCHAR(5000000),
    definitions         VARCHAR(5000000),
    sections            VARCHAR(5000000),
    transcript          VARCHAR(5000000),
    want_flashcards     BOOLEAN      NOT NULL DEFAULT FALSE,
    want_quiz           BOOLEAN      NOT NULL DEFAULT FALSE,
    flashcards_status   VARCHAR(12)  NOT NULL DEFAULT 'none',
    quiz_status         VARCHAR(12)  NOT NULL DEFAULT 'none',
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_notes_status CHECK (status IN ('queued','processing','ready','failed')),
    CONSTRAINT chk_notes_fc     CHECK (flashcards_status IN ('none','processing','ready','failed')),
    CONSTRAINT chk_notes_quiz   CHECK (quiz_status IN ('none','processing','ready','failed'))
);
CREATE INDEX idx_notes_user_created ON notes (user_id, created_at DESC);
CREATE INDEX idx_notes_status       ON notes (status);

CREATE TABLE cards (
    id            VARCHAR(40) PRIMARY KEY,
    note_id       VARCHAR(40) NOT NULL REFERENCES notes(id) ON DELETE CASCADE,
    front         VARCHAR(5000000) NOT NULL,
    back          VARCHAR(5000000) NOT NULL,
    ease          DOUBLE PRECISION NOT NULL DEFAULT 2.5,
    interval_days INTEGER NOT NULL DEFAULT 0,
    due_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    review_count  INTEGER NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_cards_note_due ON cards (note_id, due_at);

CREATE TABLE quiz_questions (
    id           VARCHAR(40) PRIMARY KEY,
    note_id      VARCHAR(40) NOT NULL REFERENCES notes(id) ON DELETE CASCADE,
    sort_order   INTEGER     NOT NULL,
    question     VARCHAR(5000000)        NOT NULL,
    options      VARCHAR(5000000)        NOT NULL,
    answer_index INTEGER     NOT NULL,
    explanation  VARCHAR(5000000),
    topic        VARCHAR(200),
    CONSTRAINT uq_quiz_note_order UNIQUE (note_id, sort_order)
);

CREATE TABLE quiz_attempts (
    id         VARCHAR(40) PRIMARY KEY,
    note_id    VARCHAR(40) NOT NULL REFERENCES notes(id) ON DELETE CASCADE,
    user_id    VARCHAR(40) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    score      INTEGER     NOT NULL,
    total      INTEGER     NOT NULL,
    mistakes   VARCHAR(5000000)        NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_attempts_note_user ON quiz_attempts (note_id, user_id, created_at DESC);

CREATE TABLE events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    VARCHAR(40) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind       VARCHAR(10) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_events_kind CHECK (kind IN ('review','quiz','note'))
);
CREATE INDEX idx_events_user_created ON events (user_id, created_at);
